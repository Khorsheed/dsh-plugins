/**
 * I5·T63 — the word table (ui-spec §九).
 *
 * What these pin is the half of 「可读性低」 that is not a stylesheet: the
 * tokens the ledger, mission and the condition contract put on the wire, and
 * the rule that decides which of them a reader may arrange the matrix by.
 *
 * Two of them are regression tests with a name. The walkthrough's matrix put
 * `["DEEPSEEK_API_KEY","DSH_HOME"]` in a column heading, because the pivot
 * takes the alphabetically first differing path and `env.keys` sorts ahead of
 * `model.declared`; and it put `home.sha`'s 64 hex characters in a filter row,
 * because the pivot reports every differing path as an equal. Both are fixed
 * on this side — {@link preferredColumn} and {@link splitFactors} — with the
 * pivot left exactly as honest as it was.
 */
import { describe, expect, it } from 'vitest'
import {
  BUCKETS, INCIDENTAL_FACTORS, NAMED_FACTORS, bucketPhrase, distinctStates, factorPhrase,
  factorValueText, isNamedFactor, preferredColumn, retryPhrase, shortHash, shortenValue, splitFactors,
  stagePhrase,
} from '../src/client/vocab.ts'
import { en, zh, type EvalKey } from '../src/client/locales.ts'

/** Every key the table can produce must exist in BOTH dictionaries. */
function bothHave(key: EvalKey): boolean {
  return typeof en[key] === 'string' && typeof zh[key] === 'string'
}

/** The absent sentinel the pivot keys a missing value with — not JSON. */
const ABSENT = String.fromCharCode(0) + 'absent'

describe('the stage words', () => {
  it('names every state a generated template walks', () => {
    // The template is `pending → ws-ready → stage-<n>… → judged | halted →
    // archived → releasable → released` (src/template.ts), which is exactly
    // the list ui-spec §九 fixes the words for.
    for (const state of [
      'pending', 'ws-ready', 'stage-1', 'stage-2', 'judged', 'halted', 'archived', 'releasable', 'released',
    ]) {
      const phrase = stagePhrase(state)
      expect(bothHave(phrase.key), `${state} → ${phrase.key}`).toBe(true)
      expect(phrase.key).not.toBe('stage.unknown')
    }
  })

  it('numbers a stage past the table rather than inventing a numeral', () => {
    // Stage states are generated by manifest POSITION, so there is no closed
    // set of them; the seventh gets the parameterized key, not `stage-7`.
    expect(stagePhrase('stage-7')).toEqual({ key: 'stage.stageN', params: { n: 7 } })
    expect(bothHave('stage.stageN')).toBe(true)
  })

  it('keeps an unknown token readable and carries the token itself', () => {
    // Total by construction: a state this table has never seen still gets a
    // word, and the token survives for whoever greps the ledger with it.
    expect(stagePhrase('teleported')).toEqual({ key: 'stage.unknown', params: { token: 'teleported' } })
  })

  it('reads a cell’s states off its reps, never off the host’s composed string', () => {
    // `mixed (archived / ws-ready)` is English tokens in English punctuation;
    // a page that parsed it back apart would break the first time the host
    // reworded it. The reps carry the states already.
    expect(distinctStates([
      { state: 'ws-ready' }, { state: 'archived' }, { state: 'archived' },
    ])).toEqual(['archived', 'ws-ready'])
  })
})

describe('the bucket and retry words', () => {
  it('names mission’s five buckets, in the order the cells page offers them', () => {
    expect(BUCKETS).toEqual(['ready', 'scheduled', 'blocked', 'active', 'done'])
    for (const bucket of BUCKETS) expect(bothHave(bucketPhrase(bucket).key)).toBe(true)
  })

  it('names mission’s three retry categories', () => {
    for (const category of ['infrastructure', 'operator', 'outcome']) {
      expect(bothHave(retryPhrase(category).key)).toBe(true)
    }
    expect(retryPhrase('whatever')).toEqual({ key: 'retry.cat.other', params: { token: 'whatever' } })
  })
})

describe('the factor table', () => {
  it('has a word for every leaf the condition contract can produce', () => {
    // The paths are `dataseek.condition/1`’s own leaves (src/schema.ts);
    // `notes` is excluded from the diff, so it is never a factor.
    for (const path of [...NAMED_FACTORS, ...INCIDENTAL_FACTORS]) {
      const phrase = factorPhrase(path)
      expect(bothHave(phrase.key), `${path} → ${phrase.key}`).toBe(true)
      expect(phrase.key).not.toBe('factor.other')
    }
  })

  it('gives an unmapped path a word and keeps the path for the title', () => {
    expect(factorPhrase('future.field')).toEqual({ key: 'factor.other', params: { path: 'future.field' } })
  })

  it('separates the designed factors from the ones that follow from them', () => {
    // `unit.scopedHome.var` is dictated by the harness and `home.sha` by
    // whatever the provisioned home holds: a reader cannot hold either fixed
    // while varying the other, so neither is ever a control.
    expect(isNamedFactor('model.declared')).toBe(true)
    expect(isNamedFactor('home.sha')).toBe(false)
    expect(isNamedFactor('unit.scopedHome.var')).toBe(false)
    expect(splitFactors(['env.keys', 'home.sha', 'model.declared', 'unit.scopedHome.var'])).toEqual({
      named: ['model.declared'],
      incidental: ['env.keys', 'home.sha', 'unit.scopedHome.var'],
    })
  })

  it('puts the designed factor on the columns, in ui-spec §九’s own order', () => {
    // The walkthrough's run: the pivot's default is `env.keys` (alphabetical),
    // and the experiment varied the model.
    expect(preferredColumn(['env.keys', 'home.sha', 'model.declared'])).toBe('model.declared')
    // §九 lists 模型 / 作用域 / 权限 / 推理强度 / harness / 版本 in that order,
    // and that order IS the preference — not an alphabetical accident.
    expect(preferredColumn(['harness.name', 'scope'])).toBe('scope')
    expect(preferredColumn(['harness.version', 'permissions'])).toBe('permissions')
    // Nothing designed varies: the page still needs a column, so the first
    // derived field carries it rather than the matrix collapsing. The pivot
    // hands these over sorted (`conditionFactors`), and that order is kept.
    expect(preferredColumn(['env.keys', 'home.sha'])).toBe('env.keys')
    expect(preferredColumn([])).toBeNull()
  })
})

describe('the value and digest formatting', () => {
  it('turns an array value into a list a person reads', () => {
    // THE heading from the walkthrough. It is a subtitle now, and never JSON.
    expect(factorValueText('["DEEPSEEK_API_KEY","DSH_HOME"]', '["DEEPSEEK_API_KEY","DSH_HOME"]'))
      .toEqual({ text: 'DEEPSEEK_API_KEY · DSH_HOME', title: '["DEEPSEEK_API_KEY","DSH_HOME"]' })
  })

  it('prints a string value as itself and a null one as a dash', () => {
    expect(factorValueText('"v4-flash"', 'v4-flash').text).toBe('v4-flash')
    expect(factorValueText('null', 'null').text).toBe('—')
  })

  it('falls back to the host’s label for the absent sentinel, which is not JSON', () => {
    expect(factorValueText(ABSENT, '—')).toEqual({ text: '—', title: '—' })
  })

  it('shortens a VALUE that happens to be a digest', () => {
    // `home.sha` reaches the page twice — the matrix's folded list of derived
    // fields, and the two-condition diff — and it is 64 hex characters.
    expect(shortenValue('"' + 'a'.repeat(64) + '"')).toBe(`${'a'.repeat(12)}…`)
    // A word is a word: nothing short or non-hex is touched.
    expect(shortenValue('v4-flash')).toBe('v4-flash')
    expect(shortenValue('"unrestricted"')).toBe('"unrestricted"')
  })

  it('shortens a digest to twelve and keeps a kind prefix', () => {
    expect(shortHash('a'.repeat(64))).toBe(`${'a'.repeat(12)}…`)
    expect(shortHash('lab-env:2e02ebee1234567890')).toBe('lab-env:2e02ebee1234…')
    // Short enough already, or absent: nothing is invented.
    expect(shortHash('c0ffee1')).toBe('c0ffee1')
    expect(shortHash(null)).toBe('—')
  })
})
