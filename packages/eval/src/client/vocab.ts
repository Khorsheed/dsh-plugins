/**
 * The word for one condition field path.
 * @param path - the dotted leaf path the diff named.
 * @returns the phrase to render; an unmapped path renders as 「其它字段」and
 *   the caller keeps the path itself in a `title`.
 */
export function factorPhrase(path: string): Phrase {
  const known = FACTOR_KEYS[path]
  return known === undefined ? { key: 'factor.other', params: { path } } : { key: known }
}

/**
 * Whether a factor may be a control (column / band / filter).
 * @param path - the dotted leaf path.
 * @returns true for a designed factor, false for a derived one.
 */
export function isNamedFactor(path: string): boolean {
  return NAMED_FACTORS.includes(path)
}

/**
 * Split a run's factor set the way the matrix page arranges it.
 * @param factors - every path the run's conditions disagree on.
 * @returns the designed factors in ui-spec order, then everything else.
 */
export function splitFactors(factors: readonly string[]): { named: string[]; incidental: string[] } {
  const named = NAMED_FACTORS.filter(path => factors.includes(path))
  const incidental = factors.filter(path => !named.includes(path))
  return { named, incidental }
}

/**
 * Which factor belongs on the columns.
 *
 * The host takes the first factor when the request names none, and the first
 * is ALPHABETICAL — which is how `env.keys` became the column of a walkthrough
 * whose experiment varied the model, and how a JSON array became a column
 * heading. The browser half knows which fields are designed factors, so it
 * asks for one.
 * @param factors - every path the run's conditions disagree on.
 * @returns the preferred column, or null when the conditions agree on all.
 */
export function preferredColumn(factors: readonly string[]): string | null {
  const { named, incidental } = splitFactors(factors)
  return named[0] ?? incidental[0] ?? null
}

/**
 * A factor VALUE, as a person reads it.
 *
 * The wire carries the canonical JSON of the value, and the host's own label
 * is that JSON verbatim for anything that is not a string — which is how
 * `["DEEPSEEK_API_KEY","DSH_HOME"]` became a matrix column heading. Leaves are
 * scalars or arrays (the flattening descends into objects), so an array turns
 * into a list a person reads and everything else prints itself.
 * @param key - the canonical JSON of the value, or the absent sentinel.
 * @param label - the host's own label, used when the key is not JSON at all.
 * @returns the text to show, and the exact value for the `title` beside it.
 */
export function factorValueText(key: string, label: string): { text: string; title: string } {
  let parsed: unknown
  try {
    parsed = JSON.parse(key)
  } catch {
    // The absent sentinel and nothing else: the host already labelled it «—».
    return { text: label, title: label }
  }
  if (parsed === null) return { text: '—', title: key }
  if (typeof parsed === 'string') return { text: parsed === '' ? '—' : parsed, title: parsed }
  if (Array.isArray(parsed)) {
    const items = parsed.map(entry => (typeof entry === 'string' ? entry : JSON.stringify(entry)))
    return { text: items.length === 0 ? '—' : items.join(' · '), title: key }
  }
  return { text: String(parsed), title: key }
}

/**
 * The distinct ledger states a group of reps sits in, sorted.
 *
 * Computed from the reps rather than read off the host's composed `stage`
 * string: that string is `mixed (archived / ws-ready)` — English tokens glued
 * into English punctuation — and a page that parsed it back apart to translate
 * it would break the first time the host reworded it.
 * @param reps - the cell's reps.
 * @returns the distinct state tokens, sorted.
 */
export function distinctStates(reps: ReadonlyArray<{ state: string }>): string[] {
  return [...new Set(reps.map(rep => rep.state))].sort()
}

/**
 * Shorten a VALUE that happens to be a digest.
 *
 * Condition values are short words (`v4-flash`, `unrestricted`) with one
 * exception: `home.sha` is 64 hex characters, and it reaches the page twice —
 * in the matrix's folded list of derived fields, and in the two-condition diff
 * table. ui-spec §九 caps a hash at twelve wherever it is shown, so the same
 * rule applies to a value that is one.
 * @param text - the value as a person would read it.
 * @returns the text, with a bare digest shortened.
 */
export function shortenValue(text: string): string {
  const bare = text.replace(/^"|"$/g, '')
  return /^[0-9a-f]{32,}$/i.test(bare) ? shortHash(bare) : text
}
