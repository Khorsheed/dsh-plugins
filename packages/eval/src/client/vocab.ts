/**
 * The word for one condition field path.
 * @param path - the dotted leaf path the diff named.
 * @returns the phrase to render; an unmapped path renders as 「其它字段」and
 *   the caller keeps the path itself in a `title`.
 */
export function factorPhrase(path: string): Phrase {
  const known = FACTOR_KEYS[path]
  return known === undefined ? { key: 'factor.other', params: { path } } : { key: known }
}

/**
 * Whether a factor may be a control (column / band / filter).
 * @param path - the dotted leaf path.
 * @returns true for a designed factor, false for a derived one.
 */
export function isNamedFactor(path: string): boolean {
  return NAMED_FACTORS.includes(path)
}

/**
 * Split a run's factor set the way the matrix page arranges it.
 * @param factors - every path the run's conditions disagree on.
 * @returns the designed factors in ui-spec order, then everything else.
 */
export function splitFactors(factors: readonly string[]): { named: string[]; incidental: string[] } {
  const named = NAMED_FACTORS.filter(path => factors.includes(path))
  const incidental = factors.filter(path => !named.includes(path))
  return { named, incidental }
}

/**
 * Which factor belongs on the columns.
 *
 * The host takes the first factor when the request names none, and the first
 * is ALPHABETICAL — which is how `env.keys` became the column of a walkthrough
 * whose experiment varied the model, and how a JSON array became a column
 * heading. The browser half knows which fields are designed factors, so it
 * asks for one.
 * @param factors - every path the run's conditions disagree on.
 * @returns the preferred column, or null when the conditions agree on all.
 */
export function preferredColumn(factors: readonly string[]): string | null {
  const { named, incidental } = splitFactors(factors)
  return named[0] ?? incidental[0] ?? null
}

/**
 * A factor VALUE, as a person reads it.
 *
 * The wire carries the canonical JSON of the value, and the host's own label
 * is that JSON verbatim for anything that is not a string — which is how
 * `["DEEPSEEK_API_KEY","DSH_HOME"]` became a matrix column heading. Leaves are
 * scalars or arrays (the flattening descends into objects), so an array turns
 * into a list a person reads and everything else prints itself.
 * @param key - the canonical JSON of the value, or the absent sentinel.
 * @param label - the host's own label, used when the key is not JSON at all.
 * @returns the text to show, and the exact value for the `title` beside it.
 */
export function factorValueText(key: string, label: string): { text: string; title: string } {
  let parsed: unknown
  try {
    parsed = JSON.parse(key)
  } catch {
    // The absent sentinel and nothing else: the host already labelled it «—».
    return { text: label, title: label }
  }
  if (parsed === null) return { text: '—', title: key }
  if (typeof parsed === 'string') return { text: parsed === '' ? '—' : parsed, title: parsed }
  if (Array.isArray(parsed)) {
    const items = parsed.map(entry => (typeof entry === 'string' ? entry : JSON.stringify(entry)))
    return { text: items.length === 0 ? '—' : items.join(' · '), title: key }
  }
  return { text: String(parsed), title: key }
}

/**
 * The distinct ledger states a group of reps sits in, sorted.
 *
 * Computed from the reps rather than read off the host's composed `stage`
 * string: that string is `mixed (archived / ws-ready)` — English tokens glued
 * into English punctuation — and a page that parsed it back apart to translate
 * it would break the first time the host reworded it.
 * @param reps - the cell's reps.
 * @returns the distinct state tokens, sorted.
 */
export function distinctStates(reps: ReadonlyArray<{ state: string }>): string[] {
  return [...new Set(reps.map(rep => rep.state))].sort()
}

/**
 * Shorten a VALUE that happens to be a digest.
 *
 * Condition values are short words (`v4-flash`, `unrestricted`) with one
 * exception: `home.sha` is 64 hex characters, and it reaches the page twice —
 * in the matrix's folded list of derived fields, and in the two-condition diff
 * table. ui-spec §九 caps a hash at twelve wherever it is shown, so the same
 * rule applies to a value that is one.
 * @param text - the value as a person would read it.
 * @returns the text, with a bare digest shortened.
 */
export function shortenValue(text: string): string {
  const bare = text.replace(/^"|"$/g, '')
  return /^[0-9a-f]{32,}$/i.test(bare) ? shortHash(bare) : text
}

/* ───────────────── numbers and sentences (ui-spec §九, 2026-09-18) ────────── */

/**
 * A count a person reads at a glance: `31.5k`, `1.2M`.
 *
 * Token counts run to six figures and `toLocaleString` prints every one of
 * them, which is how the efficiency table turned into a wall of digits. Below
 * a thousand nothing is rounded — those numbers are small enough to mean
 * something exactly (rounds, tool calls), and rounding them would hide a 1.
 * @param value - the count, or null when nobody counted.
 * @returns the compact form; an em dash for null (a dash is not a zero).
 */
export function compactCount(value: number | null): string {
  if (value === null) return '—'
  const abs = Math.abs(value)
  if (abs < 1000) return String(value)
  if (abs < 1_000_000) {
    const k = value / 1000
    return `${Math.abs(k) < 100 ? k.toFixed(1).replace(/\.0$/, '') : String(Math.round(k))}k`
  }
  const m = value / 1_000_000
  return `${Math.abs(m) < 100 ? m.toFixed(1).replace(/\.0$/, '') : String(Math.round(m))}M`
}

/** A duration split into the two units a reader actually wants. */
export interface DurationParts {
  key: EvalKey
  params: Record<string, number>
}

/**
 * Split a duration into the largest two units that carry information.
 *
 * The phrase itself is the dictionary's — 「4 分 48 秒」 and `4m 48s` are not
 * the same string with a different number in it, so the shape is chosen here
 * and the words are chosen there.
 * @param ms - the duration; null when the ledger does not say.
 * @returns the key and parameters, or null for «—».
 */
export function durationParts(ms: number | null): DurationParts | null {
  if (ms === null) return null
  const total = Math.max(0, Math.round(ms / 1000))
  if (total < 60) return { key: 'dur.s', params: { s: total } }
  const minutes = Math.floor(total / 60)
  if (minutes < 60) return { key: 'dur.ms', params: { m: minutes, s: total % 60 } }
  const hours = Math.floor(minutes / 60)
  if (hours < 24) return { key: 'dur.hm', params: { h: hours, m: minutes % 60 } }
  return { key: 'dur.dh', params: { d: Math.floor(hours / 24), h: hours % 24 } }
}

/** How much two graders agree, as the word a reader acts on. */
export type AgreementBand = 'high' | 'medium' | 'low'

/**
 * The band one κ falls in.
 *
 * The cut points are Landis & Koch's, collapsed to three: a grader reading
 * this page decides one thing — whether to trust the verdicts or add a judge —
 * and six bands do not help them decide it. κ itself stays on the hover, so
 * nothing is rounded away.
 * @param kappa - Cohen's κ, or null when there were not enough pairs.
 * @returns the band, or null when there is no number to band.
 */
export function agreementBand(kappa: number | null): AgreementBand | null {
  if (kappa === null || Number.isNaN(kappa)) return null
  if (kappa >= 0.8) return 'high'
  if (kappa >= 0.6) return 'medium'
  return 'low'
}

/* ───────────────── the verdict source (ui-spec §五 v2, I5·T67) ───────────── */

/** The three namespaces a verdict can be written in, most authoritative first. */
export type VerdictSource = 'human-final' | 'llm-draft' | 'script'

/**
 * The verdict AUTHORITY order the report scores by. Applied PER CRITERION
 * since I5·T54 — each criterion takes the most authoritative layer that
 * judged it, so one cell's score can come from several at once — but the
 * order itself is the same one, and it is what the run-record list sorts a
 * cell's namespaces by to name the source it carries.
 */
const VERDICT_ORDER: readonly VerdictSource[] = ['human-final', 'llm-draft', 'script']

/** Each source's word — one dictionary entry per source, no key arithmetic. */
const VERDICT_KEYS: Readonly<Record<VerdictSource, EvalKey>> = {
  'human-final': 'verdict.human',
  'llm-draft': 'verdict.llm',
  'script': 'verdict.script',
}

/**
 * The most authoritative source a cell carries anything in.
 *
 * What this is NOT: the score, nor a claim that the whole cell scored from
 * this one layer — since I5·T54 the merge is per criterion and a cell may mix
 * them; the mixture is on the RESULTS page, beside the number it explains.
 * The cell projection carries how MANY verdicts each namespace holds, never
 * their values, and the number a reader compares is `report.ts`'s — polarity
 * from the rubric, the best layer per criterion, majority over samples,
 * weights where the rubric carries them. Computing a
 * second one here from the live ledger would give the run records a number
 * that can disagree with the results page about the same cell, which is worse
 * than not showing one. The source IS shown, because 「这格判了没有、谁判的」 is
 * a fact this projection does hold, and it is what the run-record list is
 * scanned for.
 * @param annotations - ns → how many annotations the cell carries.
 * @returns the most authoritative source with anything recorded, or null.
 */
export function verdictSourceOf(annotations: Readonly<Record<string, number>>): VerdictSource | null {
  return VERDICT_ORDER.find(ns => (annotations[ns] ?? 0) > 0) ?? null
}

/**
 * The word for one verdict source.
 * @param source - the namespace, or null when the cell carries no verdict.
 * @returns the dictionary key to render.
 */
export function verdictKey(source: VerdictSource | null): EvalKey {
  return source === null ? 'verdict.none' : VERDICT_KEYS[source]
}

/**
 * EVERY layer this cell carries a verdict in, most authoritative first.
 *
 * The companion of {@link verdictSourceOf}, and the reason it has one: since
 * the per-criterion merge (I5·T54) a cell's score can come from several
 * layers, so naming only the top one reads as a claim about the whole record
 * that the report does not make. This still counts ANNOTATIONS, never
 * criteria — the split per criterion is the report's, from the bundle.
 * @param annotations - ns → how many annotations the cell carries.
 * @returns the sources present, authority order; empty for an unjudged cell.
 */
export function verdictSourcesOf(annotations: Readonly<Record<string, number>>): VerdictSource[] {
  return VERDICT_ORDER.filter(ns => (annotations[ns] ?? 0) > 0)
}

/** The SHORT word for each source — what fits inside a table cell. */
const SOURCE_KEYS: Readonly<Record<VerdictSource, EvalKey>> = {
  'human-final': 'source.human',
  'llm-draft': 'source.llm',
  'script': 'source.script',
}

/**
 * Narrow a recorded namespace to one of the three the report knows.
 * @param ns - the `ns` a projected verdict carries.
 * @returns the source, or null for a namespace this vocabulary has no word for.
 */
export function sourceOf(ns: string): VerdictSource | null {
  return VERDICT_ORDER.find(source => source === ns) ?? null
}

/** One layer's share of a criteria-table cell. */
export interface SourceShare {
  source: VerdictSource
  key: EvalKey
  /** Criteria (or reps) that scored from this layer. */
  count: number
}

/**
 * Where a criteria-table cell's score came from, most authoritative first.
 *
 * Since the per-criterion merge (I5·T54) a cell can score from SEVERAL layers
 * at once — a person re-judged one criterion, the judge still holds the rest —
 * and the mixture is the thing a reader has to be able to see. The counts are
 * returned rather than a sentence: a cell with one layer prints the word
 * alone («人»), because «人 4» about a cell nobody else judged counts nothing.
 * @param sources - layer → how many scored from it, as the report projected it.
 * @returns one entry per layer present, authority order, most authoritative first.
 */
export function sourceShares(sources: Readonly<Record<string, number>>): SourceShare[] {
  return VERDICT_ORDER
    .filter(source => (sources[source] ?? 0) > 0)
    .map(source => ({ source, key: SOURCE_KEYS[source], count: sources[source] as number }))
}
