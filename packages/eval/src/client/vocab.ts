/**
 * The tab's WORD TABLE (ui-spec §九): every internal token this plugin puts on
 * screen — a ledger state, a projection bucket, a condition field path, a
 * retry category — resolved to one dictionary key, so the same fact reads the
 * same way on the list, the matrix, the cells page and the report.
 *
 * WHY a module rather than `t(\`stage.${state}\`)` at each site: the tokens are
 * not a closed union on the wire. The stage states are GENERATED from the
 * dataset's manifest (`stage-<n>` by position), buckets come from mission's
 * projection, and the factor paths are whatever leaves two condition documents
 * happen to disagree on. A template literal would compile against a key union
 * it cannot actually satisfy, and the first unmapped token would render as the
 * raw key. Every lookup here is total: an unknown token gets a word, and the
 * token itself survives in the `title` the caller puts beside it.
 *
 * WHY the factor table splits NAMED from INCIDENTAL. ui-spec §九 says the
 * columns of the matrix are chosen among 「模型 / 作用域 / 权限 / 推理强度 /
 * harness / 版本」, and the I5 walkthrough found the page offering
 * `unit.scopedHome.var` and a 64-hex `home.sha` beside them as equals. Those
 * two are not designed factors — they are DERIVED: a harness implies the
 * variable naming its credential directory, and a provisioned scoped home
 * implies its digest. A reader cannot hold one fixed while varying another, so
 * they are never controls. They are still shown (folded, under their human
 * name) because they do make two conditions two subjects.
 *
 * This file is the eval half; `packages/datasets/src/client/vocab.ts` is the
 * same table minus the factors, duplicated rather than imported for the reason
 * ui-spec §八 gives (a client bundle never imports a sibling plugin).
 */

import type { EvalKey } from './locales.ts'

/** How many hex characters of a digest reach the page (ui-spec §九). */
export const HASH_WIDTH = 12

/**
 * Shorten one digest for display. The full value belongs in a `title` or a
 * «详情» fold, never in a cell or a heading.
 * @param value - the digest, possibly prefixed (`lab-env:2e02eb…`).
 * @returns the first {@link HASH_WIDTH} characters of the hex half, ellipsized.
 */
export function shortHash(value: string | null): string {
  if (value === null || value === '') return '—'
  // A prefixed digest (`lab-env:<hex>`) keeps its prefix: the prefix is the
  // kind, and dropping it would make two kinds look like one.
  const cut = value.lastIndexOf(':')
  const prefix = cut === -1 ? '' : value.slice(0, cut + 1)
  const hex = cut === -1 ? value : value.slice(cut + 1)
  return hex.length <= HASH_WIDTH ? value : `${prefix}${hex.slice(0, HASH_WIDTH)}…`
}

/** The template states a generated run walks, in order, as dictionary keys. */
const STAGE_KEYS: Readonly<Record<string, EvalKey>> = {
  'pending': 'stage.pending',
  'ws-ready': 'stage.ws-ready',
  'judged': 'stage.judged',
  'halted': 'stage.halted',
  'archived': 'stage.archived',
  'releasable': 'stage.releasable',
  'released': 'stage.released',
}

/** `stage-<n>` up to the sixth; past that the numbered fallback carries it. */
const STAGE_N_KEYS: readonly EvalKey[] = [
  'stage.stage-1', 'stage.stage-2', 'stage.stage-3', 'stage.stage-4', 'stage.stage-5', 'stage.stage-6',
]

/** What a stage word needs from the dictionary: the key, and any parameter. */
export interface Phrase {
  key: EvalKey
  params?: Record<string, string | number>
}

/**
 * The word for one template state.
 *
 * Stage states are generated by manifest position (`stage-1`, `stage-2`, …),
 * so the numbered ones resolve through a small table and anything past it
 * through a parameterized key rather than through a fabricated numeral.
 * @param state - the ledger's own state token.
 * @returns the phrase to render; unknown tokens get the token as a parameter.
 */
export function stagePhrase(state: string): Phrase {
  const known = STAGE_KEYS[state]
  if (known !== undefined) return { key: known }
  const numbered = /^stage-(\d+)$/.exec(state)
  if (numbered !== null) {
    const position = Number(numbered[1])
    const key = STAGE_N_KEYS[position - 1]
    return key === undefined ? { key: 'stage.stageN', params: { n: position } } : { key }
  }
  return { key: 'stage.unknown', params: { token: state } }
}

/** mission's five projection buckets. */
const BUCKET_KEYS: Readonly<Record<string, EvalKey>> = {
  ready: 'bucket.ready',
  scheduled: 'bucket.scheduled',
  blocked: 'bucket.blocked',
  active: 'bucket.active',
  done: 'bucket.done',
}

/** The five buckets in the order the cells page offers them. */
export const BUCKETS: readonly string[] = ['ready', 'scheduled', 'blocked', 'active', 'done']

/**
 * The word for one projection bucket.
 * @param bucket - mission's bucket token.
 * @returns the phrase to render.
 */
export function bucketPhrase(bucket: string): Phrase {
  const known = BUCKET_KEYS[bucket]
  return known === undefined ? { key: 'bucket.other', params: { token: bucket } } : { key: known }
}

